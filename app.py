def gaussienne(x, c, sigma):
    """
    Fonction d'appartenance gaussienne.

    Paramètres
    ----------
    x     : float ou np.array  — valeur(s) d'entrée
    c     : float              — centre (moyenne)
    sigma : float              — écart-type (largeur)

    Retour
    ------
    mu : float ou np.array — degré d'appartenance dans [0, 1]

    Formule
    -------
    mu(x) = exp( -(x - c)² / (2 * sigma²) )
    """
    return np.exp(-((x - c) ** 2) / (2 * sigma ** 2))


def triangulaire(x, a, b, c):
    """
    Fonction d'appartenance triangulaire.

    Paramètres
    ----------
    a, b, c : sommets du triangle (a < b < c)

    Formule
    -------
    0             si x <= a
    (x-a)/(b-a)  si a < x <= b
    (c-x)/(c-b)  si b < x <= c
    0             si x > c
    """
    return np.maximum(0, np.minimum((x - a) / (b - a + 1e-10),
                                    (c - x) / (c - b + 1e-10)))


def trapezoidale(x, a, b, c, d):
    """
    Fonction d'appartenance trapézoïdale.

    Paramètres
    ----------
    a, b, c, d : points de la base (a < b <= c < d)

    Formule
    -------
    0             si x < a
    (x-a)/(b-a)  si a <= x < b
    1             si b <= x <= c
    (d-x)/(d-c)  si c < x <= d
    0             si x > d
    """
    gauche  = np.minimum(1, np.maximum(0, (x - a) / (b - a + 1e-10)))
    droite  = np.minimum(1, np.maximum(0, (d - x) / (d - c + 1e-10)))
    return np.minimum(gauche, droite)


def sigmoide(x, a, c):
    """
    Fonction sigmoïde floue.
    a > 0 : croissante ; a < 0 : décroissante
    """
    return 1 / (1 + np.exp(-a * (x - c)))


