class ANFIS:
    """
    Système d'Inférence Neuro-Flou Adaptatif (ANFIS)
    Implémentation from scratch — Sugeno de type 1.

    Architecture (5 couches)
    ------------------------
    Couche 1 : Fuzzification (fonctions gaussiennes)
    Couche 2 : Produit — forces de règles
    Couche 3 : Normalisation des forces
    Couche 4 : Conséquents linéaires (Sugeno)
    Couche 5 : Sortie globale (somme pondérée)

    Algorithme d'apprentissage : hybride
    - Passe avant  : moindres carrés (LSE) pour les conséquents
    - Passe arrière: descente de gradient pour les prémisses
    """

    def __init__(self, n_regles=6, n_entrees=3, eta=0.005):
        """
        Initialise l'ANFIS.

        Paramètres
        ----------
        n_regles  : nombre de règles floues
        n_entrees : nombre de variables d'entrée
        eta       : taux d'apprentissage (descente de gradient)
        """
        self.n_regles  = n_regles
        self.n_entrees = n_entrees
        self.eta       = eta

        # ── Paramètres PRÉMISSES ──────────────────────────────
        # premises[r, i, 0] = centre c_{r,i}
        # premises[r, i, 1] = sigma σ_{r,i}
        # Initialisation uniforme (centres espacés, sigma = 0.2)
        self.premises = np.zeros((n_regles, n_entrees, 2))
        for r in range(n_regles):
            for i in range(n_entrees):
                self.premises[r, i, 0] = (r + 1) / (n_regles + 1)  # centre
                self.premises[r, i, 1] = 0.25                        # sigma

        # ── Paramètres CONSÉQUENTS ────────────────────────────
        # Pour chaque règle r : f_r = p_{r,0}*x1 + p_{r,1}*x2 + p_{r,2}*x3 + p_{r,3}
        # Vecteur theta de taille n_regles * (n_entrees + 1)
        n_params = n_regles * (n_entrees + 1)
        self.consequents = np.random.randn(n_params) * 0.01

        # Historique pour les courbes d'apprentissage
        self.historique_train = []
        self.historique_val   = []

    # ─────────────────────────────────────────────────────────
    # COUCHES DE L'ANFIS
    # ─────────────────────────────────────────────────────────

    def couche1_fuzzification(self, X):
        """
        Couche 1 : calcule les degrés d'appartenance.

        Paramètre  : X  shape (N, n_entrees)
        Retour     : mu shape (N, n_regles, n_entrees)

        Formule    : mu[n, r, i] = exp(-(X[n,i] - c[r,i])² / (2σ[r,i]²))
        """
        N  = X.shape[0]
        mu = np.zeros((N, self.n_regles, self.n_entrees))
        for r in range(self.n_regles):
            for i in range(self.n_entrees):
                c     = self.premises[r, i, 0]
                sigma = self.premises[r, i, 1]
                mu[:, r, i] = gaussienne(X[:, i], c, sigma)
        return mu

