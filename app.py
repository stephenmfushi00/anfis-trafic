def diviser_donnees(df, ratio_train=0.8):
    """
    Divise les données en ensembles d'entraînement et de test.

    Paramètres
    ----------
    df          : DataFrame avec les colonnes normalisées
    ratio_train : proportion pour l'entraînement (défaut 80%)

    Retour
    ------
    X_train, X_test, y_train, y_test : arrays numpy
    """
    # Variables d'entrée (normalisées)
    colonnes_X = ['heure_norm', 'est_ouvrable_norm', 'trafic_prec_norm']
    X = df[colonnes_X].values       # shape (N, 3)
    y = df['trafic_norm'].values    # shape (N,)

    n_train = int(len(df) * ratio_train)
    X_train, X_test = X[:n_train], X[n_train:]
    y_train, y_test = y[:n_train], y[n_train:]

    print(f"Taille entraînement : {len(X_train)} exemples ({ratio_train*100:.0f}%)")
    print(f"Taille test         : {len(X_test)} exemples ({(1-ratio_train)*100:.0f}%)")
    return X_train, X_test, y_train, y_test

