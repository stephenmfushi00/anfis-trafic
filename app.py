# ── Régression Linéaire (from scratch) ─────────────────────
class RegressionLineaire:
    """Régression linéaire par moindres carrés."""

    def __init__(self):
        self.poids = None

    def entrainer(self, X, y):
        """Formule directe : w = (X^T X)^{-1} X^T y"""
        X_aug     = np.hstack([X, np.ones((X.shape[0], 1))])
        A         = X_aug.T @ X_aug + 1e-6 * np.eye(X_aug.shape[1])
        self.poids = np.linalg.solve(A, X_aug.T @ y)

    def predire(self, X):
        X_aug = np.hstack([X, np.ones((X.shape[0], 1))])
        return X_aug @ self.poids


# ── Réseau de Neurones MLP (from scratch) ──────────────────
class MLP:
    """
    Réseau de neurones multicouche — 1 couche cachée.
    Activation : ReLU sur la couche cachée, linéaire en sortie.
    """

    def __init__(self, n_entrees=3, n_caches=16, eta=0.01):
        self.eta = eta
        # Initialisation Xavier
        self.W1 = np.random.randn(n_entrees, n_caches) * np.sqrt(2 / n_entrees)
        self.b1 = np.zeros(n_caches)
        self.W2 = np.random.randn(n_caches, 1) * np.sqrt(2 / n_caches)
        self.b2 = np.zeros(1)

    def relu(self, x):
        return np.maximum(0, x)

    def predire(self, X):
        self.z1 = X @ self.W1 + self.b1
        self.a1 = self.relu(self.z1)
        return (self.a1 @ self.W2 + self.b2).flatten()

    def entrainer_epoque(self, X, y):
        N      = X.shape[0]
        y_pred = self.predire(X)
        erreur = y_pred - y

        # Rétropropagation
        dL_dy  = erreur / N
        dW2    = self.a1.T @ dL_dy.reshape(-1, 1)
        db2    = np.sum(dL_dy)
        dL_da1 = dL_dy.reshape(-1, 1) @ self.W2.T
        dL_dz1 = dL_da1 * (self.z1 > 0)
        dW1    = X.T @ dL_dz1
        db1    = np.sum(dL_dz1, axis=0)

        self.W2 -= self.eta * dW2
        self.b2 -= self.eta * db2
        self.W1 -= self.eta * dW1
        self.b1 -= self.eta * db1
        return ANFIS.rmse(y, y_pred)


