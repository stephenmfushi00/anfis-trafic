# On simule 2 ans de données horaires de trafic urbain
# Profil réaliste : pics matin (7-9h) et soir (17-19h),
# réduction le weekend, bruit aléatoire

def generer_donnees_trafic(n_jours=365, graine=42):
    """
    Génère un jeu de données de trafic routier simulé.

    Variables générées
    ------------------
    - heure       : heure de la journée (0–23)
    - jour_semaine: 0=lundi ... 6=dimanche
    - est_ouvrable: 1 si jour ouvrable, 0 si weekend
    - trafic_prec : volume de trafic à t-1 (véh/h)
    - trafic      : volume de trafic à t (véh/h) — CIBLE

    Retour
    ------
    DataFrame pandas avec toutes les colonnes
    """
    np.random.seed(graine)
    donnees = []

    for jour in range(n_jours):
        jour_semaine = jour % 7         # 0=lundi, 6=dimanche
        est_ouvrable = 1 if jour_semaine < 5 else 0

        for heure in range(24):
            # --- Profil horaire de base ---
            if est_ouvrable:
                # Deux pics : matin (8h) et soir (18h)
                pic_matin = 900 * gaussienne(heure, 8, 1.5)
                pic_soir  = 1000 * gaussienne(heure, 18, 1.5)
                base      = 150  # trafic de fond
                trafic    = base + pic_matin + pic_soir
            else:
                # Weekend : un seul pic léger (13h)
                pic_midi = 500 * gaussienne(heure, 13, 2.5)
                base     = 80
                trafic   = base + pic_midi

            # --- Variations aléatoires réalistes ---
            bruit     = np.random.normal(0, 40)      # bruit gaussien
            variation = np.random.uniform(0.85, 1.15) # variation ±15%
            trafic    = max(0, trafic * variation + bruit)
            trafic    = min(trafic, 1500)             # plafond 1500 véh/h

            donnees.append({
                'heure'       : heure,
                'jour_semaine': jour_semaine,
                'est_ouvrable': est_ouvrable,
                'trafic'      : round(trafic, 1)
            })

    df = pd.DataFrame(donnees)

    # Ajouter le trafic précédent (variable autoregressive)
    df['trafic_prec'] = df['trafic'].shift(1).fillna(df['trafic'].mean())

    # Normaliser les variables dans [0, 1] pour l'ANFIS
    df['heure_norm']       = df['heure'] / 23.0
    df['est_ouvrable_norm']= df['est_ouvrable'].astype(float)
    df['trafic_prec_norm'] = df['trafic_prec'] / 1500.0
    df['trafic_norm']      = df['trafic'] / 1500.0

    return df

