def predire_trafic(heure, est_ouvrable, trafic_prec):
    """
    Prédit le volume de trafic pour un moment donné.

    Paramètres
    ----------
    heure         : int   — heure de la journée (0–23)
    est_ouvrable  : int   — 1 si jour ouvrable, 0 si weekend
    trafic_prec   : float — trafic observé à t-1 (véh/h)

    Retour
    ------
    trafic_predit : float (véh/h)
    """
    x = np.array([[
        heure / 23.0,
        float(est_ouvrable),
        trafic_prec / 1500.0
    ]])
    pred = anfis.predire(x)[0] * 1500
    return max(0, pred)


