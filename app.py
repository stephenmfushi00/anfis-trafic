    def couche3_normalisation(self, w):
        """
        Couche 3 : normalisation des forces de règles.

        Paramètre : w     shape (N, n_regles)
        Retour    : w_bar shape (N, n_regles)

        Formule   : w_bar[n, r] = w[n, r] / somme_k w[n, k]
        """
        w_somme = np.sum(w, axis=1, keepdims=True) + 1e-10
        return w / w_somme

    def couche4_5_sortie(self, X, w_bar):
        """
        Couches 4 et 5 : sortie de l'ANFIS.

        Couche 4 : contribution de chaque règle
                   O4[n, r] = w_bar[n, r] * f_r(X[n])
                   avec f_r(x) = p0*x1 + p1*x2 + p2*x3 + p3

        Couche 5 : somme totale
                   y_pred[n] = somme_r O4[n, r]

        Retour : (y_pred shape (N,), phi shape (N, n_params))
        """
        N     = X.shape[0]
        n_p   = self.n_entrees + 1
        phi   = np.zeros((N, self.n_regles * n_p))

        for r in range(self.n_regles):
            debut = r * n_p
            # Termes linéaires : w_bar * x_i
            phi[:, debut:debut + self.n_entrees] = (
                w_bar[:, r:r+1] * X
            )
            # Terme biais : w_bar
            phi[:, debut + self.n_entrees] = w_bar[:, r]

        y_pred = phi @ self.consequents   # (N,)
        return y_pred, phi

    # ─────────────────────────────────────────────────────────
    # PASSAGE AVANT COMPLET
    # ─────────────────────────────────────────────────────────

    def passage_avant(self, X):
        """
        Passage avant complet à travers les 5 couches.

        Retour : dict avec toutes les sorties intermédiaires
        """
        mu    = self.couche1_fuzzification(X)
        w     = self.couche2_regles(mu)
        w_bar = self.couche3_normalisation(w)
        y_pred, phi = self.couche4_5_sortie(X, w_bar)
        return {
            'mu'    : mu,
            'w'     : w,
            'w_bar' : w_bar,
            'phi'   : phi,
            'y_pred': y_pred
        }

    # ─────────────────────────────────────────────────────────
    # MÉTHODE DES MOINDRES CARRÉS (LSE)
    # ─────────────────────────────────────────────────────────

    def lse(self, phi, y):
        """
        Identifie les paramètres conséquents par moindres carrés.

        Formule : theta = (Phi^T Phi)^{-1} Phi^T y

        Paramètres
        ----------
        phi : matrice des régresseurs (N, n_params)
        y   : cibles (N,)
        """
        # Ajout d'une régularisation Ridge pour éviter la singularité
        lamb = 1e-4
        A    = phi.T @ phi + lamb * np.eye(phi.shape[1])
        b    = phi.T @ y
        self.consequents = np.linalg.solve(A, b)

    # ─────────────────────────────────────────────────────────
    # DESCENTE DE GRADIENT (paramètres prémisses)
    # ─────────────────────────────────────────────────────────

    def descente_gradient(self, X, y, res):
        """
        Met à jour les paramètres prémisses par descente de gradient.

        Utilise la règle de la chaîne à travers les 5 couches.

        dE/dc_{r,i} = dE/dy * dy/dw_bar_r * dw_bar_r/dw_r
                      * dw_r/dmu_{r,i} * dmu_{r,i}/dc_{r,i}
        """
        N     = X.shape[0]
        mu    = res['mu']
        w     = res['w']
        w_bar = res['w_bar']
        y_pred= res['y_pred']
        erreur= y_pred - y           # dE/dy_pred, shape (N,)

        n_p    = self.n_entrees + 1
        w_somme= np.sum(w, axis=1) + 1e-10   # shape (N,)

        for r in range(self.n_regles):
            # ── f_r(X) : sortie de la règle r ────────────────
            debut  = r * n_p
            theta_r = self.consequents[debut:debut + n_p]
            X_aug   = np.hstack([X, np.ones((N, 1))])  # (N, n_entrees+1)
            f_r     = X_aug @ theta_r                   # (N,)

            # ── dy/dw_bar_r ───────────────────────────────────
            # y = somme_k w_bar_k * f_k
            # dy/dw_bar_r = f_r
            dy_dwbar = f_r    # shape (N,)

            # ── dw_bar_r/dw_r ─────────────────────────────────
            # w_bar_r = w_r / W  où W = somme_k w_k
            # dw_bar_r/dw_r = (W - w_r) / W²
            dwbar_dw = (w_somme - w[:, r]) / (w_somme ** 2)

            for i in range(self.n_entrees):
                c     = self.premises[r, i, 0]
                sigma = self.premises[r, i, 1]

                # ── dw_r/dmu_{r,i} ────────────────────────────
                # w_r = produit_{j} mu_{r,j}
                # dw_r/dmu_{r,i} = produit_{j≠i} mu_{r,j}
                #                = w_r / mu_{r,i}
                dw_dmu = w[:, r] / (mu[:, r, i] + 1e-10)

                # ── dmu_{r,i}/dc_{r,i} ────────────────────────
                # mu = exp(-(x-c)²/(2σ²))
                # dmu/dc = mu * (x - c) / σ²
                xi        = X[:, i]
                dmu_dc    = mu[:, r, i] * (xi - c) / (sigma ** 2)
                dmu_dsigma= mu[:, r, i] * (xi - c)**2 / (sigma ** 3)

                # ── Gradient total (règle de la chaîne) ───────
                facteur  = erreur * dy_dwbar * dwbar_dw * dw_dmu
                grad_c   = np.mean(facteur * dmu_dc)
                grad_sig = np.mean(facteur * dmu_dsigma)

                # ── Mise à jour ────────────────────────────────
                self.premises[r, i, 0] -= self.eta * grad_c
                self.premises[r, i, 1] -= self.eta * grad_sig

                # Contrainte : sigma strictement positif
                self.premises[r, i, 1] = max(self.premises[r, i, 1], 0.01)
                # Contrainte : centre dans [0, 1] (données normalisées)
                self.premises[r, i, 0] = np.clip(self.premises[r, i, 0], 0, 1)

    # ─────────────────────────────────────────────────────────
    # BOUCLE D'ENTRAÎNEMENT PRINCIPALE
    # ─────────────────────────────────────────────────────────

    def entrainer(self, X_train, y_train, X_val, y_val, n_epoques=80):
        """
        Entraîne l'ANFIS par l'algorithme hybride.

        Pour chaque époque :
          1. Passe avant  → calculer mu, w, w_bar, phi
          2. LSE          → optimiser les conséquents (theta)
          3. Passe avant  → recalculer y_pred avec nouveaux theta
          4. Passe arrière→ gradient descent sur les prémisses

        Paramètres
        ----------
        X_train, y_train : données d'entraînement
        X_val,   y_val   : données de validation
        n_epoques        : nombre d'itérations
        """
        print("=" * 55)
        print("  DÉBUT DE L'ENTRAÎNEMENT ANFIS")
        print(f"  Règles : {self.n_regles} | "
              f"Entrées : {self.n_entrees} | "
              f"Éta : {self.eta}")
        print("=" * 55)

        for epoque in range(1, n_epoques + 1):

            # ── Passe avant (train) ──────────────────────────
            res_train = self.passage_avant(X_train)

            # ── Moindres carrés (LSE) ────────────────────────
            self.lse(res_train['phi'], y_train)

            # ── Recalcul avec nouveaux conséquents ───────────
            res_train = self.passage_avant(X_train)

            # ── Passe arrière (gradient) ─────────────────────
            self.descente_gradient(X_train, y_train, res_train)

            # ── Calcul des erreurs ───────────────────────────
            rmse_train = self.rmse(y_train, res_train['y_pred'])
            res_val    = self.passage_avant(X_val)
            rmse_val   = self.rmse(y_val, res_val['y_pred'])

            self.historique_train.append(rmse_train)
            self.historique_val.append(rmse_val)

            if epoque % 10 == 0 or epoque == 1:
                print(f"  Époque {epoque:3d}/{n_epoques} | "
                      f"RMSE train : {rmse_train:.6f} | "
                      f"RMSE val : {rmse_val:.6f}")

        print("=" * 55)
        print("  ENTRAÎNEMENT TERMINÉ")
        print(f"  RMSE final train : {self.historique_train[-1]:.6f}")
        print(f"  RMSE finale val  : {self.historique_val[-1]:.6f}")
        print("=" * 55)

    # ─────────────────────────────────────────────────────────
    # PRÉDICTION
    # ─────────────────────────────────────────────────────────

    def predire(self, X):
        """
        Génère les prédictions pour X.
        Retour : y_pred shape (N,)
        """
        res = self.passage_avant(X)
        return np.clip(res['y_pred'], 0, 1)   # Forcer dans [0, 1]

    # ─────────────────────────────────────────────────────────
    # MÉTRIQUES
    # ─────────────────────────────────────────────────────────

    @staticmethod
    def rmse(y_vrai, y_pred):
        """Erreur quadratique moyenne racine."""
        return np.sqrt(np.mean((y_vrai - y_pred) ** 2))

    @staticmethod
    def mae(y_vrai, y_pred):
        """Erreur absolue moyenne."""
        return np.mean(np.abs(y_vrai - y_pred))

    @staticmethod
    def mape(y_vrai, y_pred):
        """Erreur absolue moyenne en pourcentage."""
        masque = np.abs(y_vrai) > 1e-6
        return 100 * np.mean(
            np.abs((y_vrai[masque] - y_pred[masque]) / y_vrai[masque])
        )

    @staticmethod
    def r2(y_vrai, y_pred):
        """Coefficient de détermination R²."""
        ss_res = np.sum((y_vrai - y_pred) ** 2)
        ss_tot = np.sum((y_vrai - np.mean(y_vrai)) ** 2)
        return 1 - ss_res / (ss_tot + 1e-10)


